// Package gen 代码生成工具：扫描 //plugin:export 注解并生成 plugins_gen.go。
// 用法：go run ./cmd/gen 或 go generate ./...
//
// 注解格式：//plugin:export name=<插件名> api=<主版本>.<次版本> backend=<后端名>
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// pluginExportRegex 匹配 //plugin:export 注解
var pluginExportRegex = regexp.MustCompile(`//\s*plugin:export\s+(.+)`)

// exportAttrs 解析出的注解属性
type exportAttrs struct {
	Name      string
	API       string
	Backend   string
	Extension string
}

// parseExport 注解字符串
func parseExport(annotation string) exportAttrs {
	attrs := exportAttrs{
		Backend: "builtin", // 默认后端
	}

	// 使用 strings.Split 解析 key=value 对，避免 regexp 回溯引用问题
	// 注解格式：name=value api=1.0 backend=builtin extension=notifier
	parts := strings.Split(annotation, " ")
	for _, part := range parts {
		kv := strings.SplitN(part, "=", 2)
		if len(kv) != 2 {
			continue
		}
		key := strings.ToLower(kv[0])
		value := kv[1]

		switch key {
		case "name":
			attrs.Name = value
		case "api":
			attrs.API = value
		case "backend":
			attrs.Backend = value
		case "extension":
			attrs.Extension = value
		}
	}

	return attrs
}

// findPluginFiles 扫描目录查找 .go 文件
func findPluginFiles(dir string) ([]string, error) {
	var files []string

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	for _, entry := range entries {
		if entry.IsDir() {
			// 递归扫描子目录
			subFiles, err := findPluginFiles(filepath.Join(dir, entry.Name()))
			if err != nil {
				return nil, err
			}
			files = append(files, subFiles...)
			continue
		}

		if strings.HasSuffix(entry.Name(), ".go") {
			files = append(files, filepath.Join(dir, entry.Name()))
		}
	}

	return files, nil
}

// scanFileForExport 扫描单个文件查找 //plugin:export 注解
func scanFileForExport(path string) (exportAttrs, bool) {
	// 读取文件
	data, err := os.ReadFile(path)
	if err != nil {
		return exportAttrs{}, false
	}

	text := string(data)
	matches := pluginExportRegex.FindStringSubmatch(text)
	if matches == nil {
		return exportAttrs{}, false
	}

	return parseExport(matches[1]), true
}

func capitalize(s string) string {
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// generateGenFile 生成 plugins_gen.go 内容
func generateGenFile(annotations map[string]exportAttrs) (string, error) {
	if len(annotations) == 0 {
		return "// No //plugin:export annotations found in scanned files.\n", nil
	}

	// 按名称排序，确保输出有序
	names := make([]string, 0, len(annotations))
	for name := range annotations {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf strings.Builder
	buf.WriteString("// Code generated by millipede cmd/gen.\n")
	buf.WriteString("// If you need to regenerate: go run ./cmd/gen\n")
	buf.WriteString("\n")
	buf.WriteString("package millipede\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"github.com/witchsnk/millipede/kernel/spi\"\n")
	buf.WriteString("\t\"github.com/witchsnk/millipede/sdk/contract\"\n")
	buf.WriteString(")\n\n")

	for _, name := range names {
		attrs := annotations[name]
		initFunc := fmt.Sprintf(`// Code generated by millipede cmd/gen. DO NOT EDIT.

func init() {
	registry := spi.NewRegistry[contract.%s]()
	registry.MustRegister("%s", nil)
	_ = registry
}
`, capitalize(attrs.Extension), attrs.Name)

		buf.WriteString(initFunc)
		buf.WriteString("\n")
	}

	return buf.String(), nil
}

func findModuleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

// main 是工具入口
func main() {
	rootDir, err := findModuleRoot()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error finding module root: %v\n", err)
		os.Exit(1)
	}

	// 扫描 plugins 目录
	pluginsDir := filepath.Join(rootDir, "plugins")
	files, err := findPluginFiles(pluginsDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error scanning plugins dir: %v\n", err)
		os.Exit(1)
	}

	// 收集所有注解
	annotations := make(map[string]exportAttrs)
	foundCount := 0

	for _, file := range files {
		attrs, found := scanFileForExport(file)
		if found {
			// 使用插件名作为键，避免重复
			if attrs.Name != "" {
				annotations[attrs.Name] = attrs
				foundCount++
				fmt.Printf("Found //plugin:export in %s: name=%s\n", file, attrs.Name)
			}
		}
	}

	genTarget := filepath.Join(rootDir, "plugins_gen.go")

	if foundCount == 0 {
		fmt.Println("No //plugin:export annotations found in plugins directory")
		// 仍然生成空文件，保持幂等
		genContent, _ := generateGenFile(annotations)
		os.WriteFile(genTarget, []byte(genContent), 0644)
		return
	}

	// 生成代码
	genContent, err := generateGenFile(annotations)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error generating code: %v\n", err)
		os.Exit(1)
	}

	// 写入文件
	err = os.WriteFile(genTarget, []byte(genContent), 0644)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error writing plugins_gen.go: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated plugins_gen.go with %d plugin registrations\n", foundCount)
}
